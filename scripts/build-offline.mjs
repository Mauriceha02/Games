import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile, mkdir, copyFile, rm } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

async function filesUnder(root, directory) {
  const entries = await readdir(new URL(directory, root), { withFileTypes: true });
  const groups = await Promise.all(entries.map(entry => {
    const path = `${directory}${entry.name}`;
    return entry.isDirectory() ? filesUnder(root, `${path}/`) : [path];
  }));
  return groups.flat();
}

export async function buildOffline(root = new URL('../', import.meta.url)) {
  const assets = [
    'index.html', 'manifest.webmanifest',
    'src/ui/phase-cards.css', 'src/ui/game-table.css',
    'src/game/deck.json', 'src/game/phases.json',
    ...await filesUnder(root, 'public/assets/'),
    ...await filesUnder(root, 'public/app/'),
  ].sort();
  const source = await readFile(new URL('src/storage/service-worker.js', root), 'utf8');
  const hash = createHash('sha256').update(source);
  for (const path of assets) hash.update(path).update(await readFile(new URL(path, root)));
  const revision = hash.digest('hex').slice(0, 20);
  const worker = `// Generated by npm run build.\nconst REVISION = ${JSON.stringify(revision)};\nconst ASSETS = ${JSON.stringify(assets, null, 2)};\n${source}`;
  await writeFile(new URL('sw.js', root), worker);
  const destination = new URL('dist/', root);
  await rm(destination, { recursive: true, force: true });
  for (const path of [...assets, 'sw.js']) {
    const target = new URL(path, destination);
    await mkdir(new URL('./', target), { recursive: true });
    await copyFile(new URL(path, root), target);
  }
  return { assets, revision };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { assets } = await buildOffline();
  console.log(`Offline-App gebaut: ${assets.length} Dateien, Hosting-Ordner dist/.`);
}
